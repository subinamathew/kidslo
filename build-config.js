/**
 * Zero-dependency build script to generate config.js from Environment Variables
 * Reads from process.env and local .env file (if present)
 */

const fs = require('fs');
const path = require('path');

// Helper to parse local .env file without external dependencies
const loadLocalEnv = (envFilePath) => {
  const env = {};
  if (!fs.existsSync(envFilePath)) {
    return env;
  }

  const content = fs.readFileSync(envFilePath, 'utf8');
  const lines = content.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();

      // Remove surrounding quotes if present
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
};

// Load local .env and merge with process.env
const localEnv = loadLocalEnv(path.join(__dirname, '.env'));
const getEnv = (key, fallback = '') => {
  return process.env[key] || localEnv[key] || fallback;
};

// Normalize entry ID: ensures "entry.12345" format even if user passes "12345"
const formatEntry = (val) => {
  if (!val) return '';
  return val.startsWith('entry.') ? val : `entry.${val}`;
};

// Extract configuration from environment
const GOOGLE_FORM_ID = getEnv('GOOGLE_FORM_ID', '');

if (!GOOGLE_FORM_ID) {
  console.warn('⚠️ Warning: GOOGLE_FORM_ID is not defined in environment variables or .env file.');
}

const config = {
  GOOGLE_FORM_ID: GOOGLE_FORM_ID,
  FORM_ACTION_URL: GOOGLE_FORM_ID ? `https://docs.google.com/forms/d/e/${GOOGLE_FORM_ID}/formResponse` : '',
  ENTRY_KID_NAME: formatEntry(getEnv('ENTRY_KID_NAME')),
  ENTRY_PARENT_NAME: formatEntry(getEnv('ENTRY_PARENT_NAME')),
  ENTRY_PARENT_PHONE: formatEntry(getEnv('ENTRY_PARENT_PHONE')),
  ENTRY_PICKUP_PERMISSION: formatEntry(getEnv('ENTRY_PICKUP_PERMISSION')),
  ENTRY_PICKUP_CODE: formatEntry(getEnv('ENTRY_PICKUP_CODE')),
  ENTRY_CONSENT: formatEntry(getEnv('ENTRY_CONSENT'))
};

const outputContent = `// Auto-generated by build-config.js at ${new Date().toISOString()}
// Do NOT edit this file manually. Configure via Netlify Environment Variables.
window.APP_CONFIG = ${JSON.stringify(config, null, 2)};
`;

const targetPath = path.join(__dirname, 'config.js');
fs.writeFileSync(targetPath, outputContent, 'utf8');

console.log('✓ Successfully generated config.js from Environment Variables:');
console.log(`  - Google Form ID: ${config.GOOGLE_FORM_ID ? '[Configured]' : '[Missing]'}`);
console.log(`  - Kid Name Entry: ${config.ENTRY_KID_NAME ? '[Configured]' : '[Missing]'}`);
console.log(`  - Parent Name Entry: ${config.ENTRY_PARENT_NAME ? '[Configured]' : '[Missing]'}`);
console.log(`  - Parent Phone Entry: ${config.ENTRY_PARENT_PHONE ? '[Configured]' : '[Missing]'}`);
console.log(`  - Pickup Permission Entry: ${config.ENTRY_PICKUP_PERMISSION ? '[Configured]' : '[Missing]'}`);
console.log(`  - Pickup Code Entry: ${config.ENTRY_PICKUP_CODE ? '[Configured]' : '[Missing]'}`);
console.log(`  - Consent Entry: ${config.ENTRY_CONSENT ? '[Configured]' : '[Missing]'}`);
